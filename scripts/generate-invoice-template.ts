import handlebars from "handlebars";
import { readFile, writeFile } from "node:fs/promises";
import { argv } from "node:process";

const templateDirectory = new URL("../src/templates/", import.meta.url);
const templateSource = await readFile(new URL("subscription-invoice.hbs", templateDirectory), "utf-8");
const escapedSource = templateSource.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
const generatedHeader = "// Generated by bun scripts/generate-invoice-template.ts from subscription-invoice.hbs.\n// Edit the .hbs source and regenerate; do not edit this file directly.\n";
const artifacts = [
    ["invoice-template.ts", `${generatedHeader}\nexport const subscriptionInvoiceTemplate = \`${escapedSource}\`;\n`],
    ["invoice-template.precompiled.js", `${generatedHeader}\nexport const subscriptionInvoiceTemplateSpec = ${handlebars.precompile(templateSource)};\n`],
    ["invoice-template.precompiled.d.ts", `${generatedHeader}\nexport declare const subscriptionInvoiceTemplateSpec: Parameters<typeof import("handlebars/runtime").template>[0];\n`],
] as const;

for (const [filename, contents] of artifacts) {
    const artifact = new URL(filename, templateDirectory);
    if (argv.includes("--check")) {
        if (await readFile(artifact, "utf-8") !== contents) throw new Error(`Regenerate stale invoice template: ${filename}`);
    } else {
        await writeFile(artifact, contents);
    }
}
